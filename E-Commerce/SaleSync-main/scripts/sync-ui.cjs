const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'../SaleSync_Online_Alive_v5');
const online=path.join(root,'SaleSync_Online_Alive.html');
let html=fs.readFileSync(online,'utf8');
if(!html.includes('assets/upgrade.css'))html=html.replace('</head>','<link rel="stylesheet" href="assets/upgrade.css"></head>');
if(!html.includes('assets/live.js'))html=html.replace('</body>','<script src="assets/live.js"></script></body>');
if(!html.includes('assets/commerce-ui.js'))html=html.replace('<script src="assets/live.js">','<script src="assets/commerce-ui.js"></script><script src="assets/live.js">');
if(!html.includes('assets/customer-features.js'))html=html.replace('<script src="assets/commerce-ui.js">','<script src="assets/customer-features.js"></script><script src="assets/commerce-ui.js">');
if(!html.includes('assets/experience.js'))html=html.replace('</body>','<script src="assets/experience.js"></script></body>');
if(!html.includes('assets/shopping.js'))html=html.replace('</body>','<script src="assets/shopping.js"></script></body>');
if(!html.includes('assets/variations.js'))html=html.replace('</body>','<script src="assets/variations.js"></script></body>');
if(!html.includes('assets/storefront.js'))html=html.replace('</body>','<script src="assets/storefront.js"></script></body>');
fs.writeFileSync(online,html);
const offline=path.join(root,'SaleSync_Online_Offline_Alive.html');
let embedded=fs.readFileSync(offline,'utf8');
embedded=embedded.replace(/<style id="compact-upgrade">[\s\S]*?<\/style>/,'');
embedded=embedded.replace('</head>','<style id="compact-upgrade">'+fs.readFileSync(path.join(root,'assets/upgrade.css'),'utf8')+'</style></head>');
embedded=embedded.replace(/<script id="salesync-shopping">[\s\S]*?<\/script>/,'');
embedded=embedded.replace(/<script id="salesync-experience">[\s\S]*?<\/script>/,'');
embedded=embedded.replace('</body>','<script id="salesync-experience">'+fs.readFileSync(path.join(root,'assets/experience.js'),'utf8')+'</script></body>');
embedded=embedded.replace('</body>','<script id="salesync-shopping">'+fs.readFileSync(path.join(root,'assets/shopping.js'),'utf8')+'</script></body>');
fs.writeFileSync(offline,embedded);
console.log('Updated online presentation hooks and self-contained offline presentation.');
